export function Ticks({ ack = 0, failed }) {
  if (failed) return <span className="tick tick-failed">!</span>;
  if (ack === 0) {
    return (
      <svg className="tick" width="16" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
        <circle cx="12" cy="12" r="9" />
        <path d="M12 7v5l3 2" />
      </svg>
    );
  }
  const delivered = ack >= 2;
  return (
    <svg
      className={`tick ${ack >= 3 ? 'tick-read' : ''}`}
      width="17"
      height="14"
      viewBox="0 0 18 14"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.9"
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {delivered ? (
        <>
          <path d="M1 7.6 4.3 11 11.4 3" />
          <path d="M6.6 7.6 9.9 11 17 3" />
        </>
      ) : (
        <path d="M2.5 7.6 5.8 11 13.5 3" />
      )}
    </svg>
  );
}
